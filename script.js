function initCarousel() {
  const carousel = document.querySelector('.carousel');
  if (!carousel) return;

  let isDown = false;
  let startX = 0;
  let scrollLeft = 0;
  let targetScrollLeft = carousel.scrollLeft;
  let animId = null;

  function smoothScrollStep() {
    const diff = targetScrollLeft - carousel.scrollLeft;
    if (Math.abs(diff) > 0.5) {
      carousel.scrollLeft += diff * 0.12;
      updateActiveItem();
      animId = requestAnimationFrame(smoothScrollStep);
    } else {
      carousel.scrollLeft = targetScrollLeft;
      updateActiveItem();
      animId = null;
    }
  }

  carousel.addEventListener('wheel', (e) => {
    const delta = Math.abs(e.deltaX) > Math.abs(e.deltaY) ? e.deltaX : e.deltaY;
    if (delta !== 0) {
      e.preventDefault();
      const maxScroll = carousel.scrollWidth - carousel.clientWidth;
      targetScrollLeft = Math.max(0, Math.min(maxScroll, targetScrollLeft + delta * 1.2));
      if (!animId) {
        animId = requestAnimationFrame(smoothScrollStep);
      }
    }
  }, { passive: false });

  carousel.addEventListener('mousedown', (e) => {
    isDown = true;
    carousel.classList.add('active');
    startX = e.pageX - carousel.offsetLeft;
    scrollLeft = carousel.scrollLeft;
    targetScrollLeft = scrollLeft;
    if (animId) {
      cancelAnimationFrame(animId);
      animId = null;
    }
  });

  carousel.addEventListener('mouseleave', () => {
    isDown = false;
    carousel.classList.remove('active');
  });

  carousel.addEventListener('mouseup', () => {
    isDown = false;
    carousel.classList.remove('active');
  });

  carousel.addEventListener('mousemove', (e) => {
    if (!isDown) return;
    e.preventDefault();
    const x = e.pageX - carousel.offsetLeft;
    const walk = (x - startX) * 1.5;
    carousel.scrollLeft = scrollLeft - walk;
    targetScrollLeft = carousel.scrollLeft;
    updateActiveItem();
  });

  carousel.addEventListener('touchstart', (e) => {
    isDown = true;
    startX = e.touches[0].pageX - carousel.offsetLeft;
    scrollLeft = carousel.scrollLeft;
    targetScrollLeft = scrollLeft;
    if (animId) {
      cancelAnimationFrame(animId);
      animId = null;
    }
  }, { passive: true });

  carousel.addEventListener('touchend', () => {
    isDown = false;
  });

  carousel.addEventListener('scroll', () => {
    if (!animId && !isDown) {
      targetScrollLeft = carousel.scrollLeft;
    }
    updateActiveItem();
  });

  const items = document.querySelectorAll('.carousel-item');

  function updateActiveItem() {
    let closestItem = null;
    let minDistance = Infinity;
    const focalX = 60; // Offset matching container padding-left

    items.forEach(item => {
      const rect = item.getBoundingClientRect();
      const dist = Math.abs(rect.left - focalX);
      if (dist < minDistance) {
        minDistance = dist;
        closestItem = item;
      }
    });

    items.forEach(item => {
      if (item === closestItem) {
        if (!item.classList.contains('active')) item.classList.add('active');
      } else {
        if (item.classList.contains('active')) item.classList.remove('active');
      }
    });
  }

  setTimeout(updateActiveItem, 100);
}


function initProjectDetail() {
  const container = document.querySelector('.dynamic-project-container');
  if (!container) return;

  const urlParams = new URLSearchParams(window.location.search);
  const projectId = parseInt(urlParams.get('id'));

  if (!projectId) return;

  const project = projectData.find(p => p.id === projectId);
  if (!project) return;

  // Projecttitel invullen
  const titleEl = document.getElementById('project-title');

  if (titleEl) {
    titleEl.textContent = project.title;
  }

  const projectImages = project.images || [project.src];
  const processImages = project.processImages || projectImages;

  let currentIndex = 0;
  let processIndex = 0;

  // Tekstvak 1
  let text1Content = '';

  if (project.id === 1) {
    text1Content = `
      <p>De volwassen knuffel onderzoekt waar volwassenen comfort zoeken in een wereld die steeds digitaler wordt. Waar kinderen steun vinden in een knuffel of speelgoed, zoeken volwassenen steeds vaker afleiding en bevestiging op hun telefoon.</p>
      <p>Maar hoe echt is dat gevoel van verbondenheid? De telefoon lijkt comfort te bieden, terwijl sociale media ook een onrealistisch beeld van de werkelijkheid kunnen creëren. Dit project stelt de vraag waarom we ons blijven hechten aan iets dat ons niet de geborgenheid kan geven die we zoeken.</p>
    `;
  } else if (project.detailText1) {
    text1Content = project.detailText1
      .map(p => `<p>${p}</p>`)
      .join('');
  } else {
    text1Content = `
      <p><strong>${project.title}</strong> Lorem ipsum dolor sit amet, consectetur adipiscing elit.</p>
    `;
  }

  // Tekstvak 2
  let text2Content = '';

  if (project.detailText2) {
    text2Content = project.detailText2
      .map(p => `<p>${p}</p>`)
      .join('');
  } else {
    text2Content = `
      <p>Lorem ipsum dolor sit amet, consectetur adipiscing elit.</p>
    `;
  }

  const metaHTML = `${project.client}<br>${project.type}<br><br>${project.location}<br>${project.date}`;

  // Pijlen behouden hun oorspronkelijke uiterlijk
  const arrowLeftSvg = `<svg width="22" height="16" viewBox="0 0 22 16" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M21 8H1M8 1L1 8L8 15"/></svg>`;

  const arrowRightSvg = `<svg width="22" height="16" viewBox="0 0 22 16" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"><path d="M1 8H21M14 1L21 8L14 15"/></svg>`;

  // Alleen projecten 1, 3 en 5 krijgen een extra procesafbeelding
  const showProcess = [1, 3, 5].includes(project.id);

  container.innerHTML = `
    <div class="project-grid">

      <div class="meta">
        ${metaHTML}
      </div>

      <img
        src="${project.src}"
        alt="${project.title} - Main"
        class="detail-img-1"
      >

      <div class="project-detail-yellow-block"></div>

      <div class="detail-text-1">
        ${text1Content}
      </div>

      <div class="detail-img-wrapper detail-img-2-wrapper">
        <img
          src="${projectImages[0]}"
          alt="${project.title} - Detail"
          class="detail-img-2"
          id="detail-img-2"
        >

        ${projectImages.length > 1 ? `
          <div class="img-nav-controls" id="nav-controls-2">
            <button class="arrow-btn prev-btn" id="prev-btn-2" aria-label="Vorige afbeelding">
              ${arrowLeftSvg}
            </button>
            <button class="arrow-btn next-btn" id="next-btn-2" aria-label="Volgende afbeelding">
              ${arrowRightSvg}
            </button>
          </div>
        ` : ''}
      </div>

      <div class="detail-text-2">
        ${text2Content}
      </div>

      ${showProcess ? `
        <div class="process-img-wrapper">
          <img
  src="${processImages[0]}"
  alt="${project.title} - Proces"
  class="process-img"
  id="process-img"
>

          ${projectImages.length > 1 ? `
            <div class="img-nav-controls process-nav-controls" id="process-nav-controls">
              <button class="arrow-btn prev-btn" id="process-prev-btn" aria-label="Vorige procesafbeelding">
                ${arrowLeftSvg}
              </button>
              <button class="arrow-btn next-btn" id="process-next-btn" aria-label="Volgende procesafbeelding">
                ${arrowRightSvg}
              </button>
            </div>
          ` : ''}
        </div>
      ` : ''}

    </div>
  `;

  // Navigatie van afbeelding 2
  const img2El = document.getElementById('detail-img-2');
  const prevBtn2 = document.getElementById('prev-btn-2');
  const nextBtn2 = document.getElementById('next-btn-2');

  function updateImg(index) {
    if (!projectImages.length || !img2El) return;

    currentIndex = (index + projectImages.length) % projectImages.length;
    img2El.src = projectImages[currentIndex];
  }

  if (nextBtn2) {
    nextBtn2.addEventListener('click', (e) => {
      e.stopPropagation();
      updateImg(currentIndex + 1);
    });
  }

  if (prevBtn2) {
    prevBtn2.addEventListener('click', (e) => {
      e.stopPropagation();
      updateImg(currentIndex - 1);
    });
  }

  // Onafhankelijke navigatie van de procesafbeeldingen
  const processImg = document.getElementById('process-img');
  const processPrevBtn = document.getElementById('process-prev-btn');
  const processNextBtn = document.getElementById('process-next-btn');

  function updateProcessImg(index) {
    if (!processImages.length || !processImg) return;

    processIndex = (index + processImages.length) % processImages.length;
    processImg.src = processImages[processIndex];
  }

  if (processNextBtn) {
    processNextBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      updateProcessImg(processIndex + 1);
    });
  }

  if (processPrevBtn) {
    processPrevBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      updateProcessImg(processIndex - 1);
    });
  }
}
